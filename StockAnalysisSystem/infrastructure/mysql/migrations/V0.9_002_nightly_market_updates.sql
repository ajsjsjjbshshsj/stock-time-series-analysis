-- Additive only; apply explicitly. Existing market and pool tables are untouched.
CREATE TABLE IF NOT EXISTS market_update_run (
 task_id CHAR(32) COLLATE utf8mb4_bin NOT NULL PRIMARY KEY,
 identity CHAR(64) COLLATE utf8mb4_bin NOT NULL,
 trade_date DATE NOT NULL,
 market_scope VARCHAR(16) NOT NULL,
 requirements_version VARCHAR(32) NOT NULL,
 request_json LONGTEXT NOT NULL,
 request_sha256 CHAR(64) COLLATE utf8mb4_bin NOT NULL,
 universe_json LONGTEXT NULL,
 universe_sha256 CHAR(64) COLLATE utf8mb4_bin NULL,
 attempt_no INT NOT NULL DEFAULT 1,
 not_before DATETIME(6) NOT NULL,
 status VARCHAR(24) NOT NULL,
 phase VARCHAR(24) NOT NULL,
 owner_token CHAR(32) COLLATE utf8mb4_bin NULL,
 owner_json LONGTEXT NULL,
 lease_until DATETIME(6) NULL,
 retry_not_before DATETIME(6) NULL,
 progress_json LONGTEXT NOT NULL,
 result_json LONGTEXT NULL,
 error_kind VARCHAR(32) NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 UNIQUE KEY uq_market_day (market_scope,trade_date,requirements_version),
 UNIQUE KEY uq_market_identity (identity),
 KEY idx_market_date (trade_date),
 KEY idx_market_queue (status,not_before,retry_not_before,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
